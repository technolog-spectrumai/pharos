// Third-party licence notices for one Tauri app: every crate the app's Rust
// package pulls in (cargo metadata, normal dependencies, this platform's
// set) and every npm package its window ships (dependencies, not dev).
//
//   node scripts/third_party.mjs nautes          writes nautes/THIRD_PARTY.md
//   node scripts/third_party.mjs proteus --check fails if that file is stale
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const [app, flag] = process.argv.slice(2);
if (!app) throw new Error("usage: third_party.mjs <app> [--check]");
// Pharos keeps its two programs at the root (nautes/, proteus/).
const appDir = join(root, app);
const pkgFile = join(appDir, "package.json");
const pkg = existsSync(pkgFile) ? JSON.parse(readFileSync(pkgFile, "utf8")) : { dependencies: {} };

function crates() {
  const meta = JSON.parse(execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"],
    { cwd: root, maxBuffer: 1 << 28 }));
  const byId = new Map(meta.packages.map((p) => [p.id, p]));
  const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
  const start = meta.packages.find((p) => p.name === app && p.source === null);
  const seen = new Set();
  const todo = [start.id];
  while (todo.length) {
    const id = todo.pop();
    if (seen.has(id)) continue;
    seen.add(id);
    for (const d of nodes.get(id)?.deps ?? [])
      if (d.dep_kinds.some((k) => k.kind === null)) todo.push(d.pkg);
  }
  return [...seen].map((id) => byId.get(id)).filter((p) => p.source !== null)
    .map((p) => ({ name: p.name, version: p.version, license: p.license ?? "see its repository", url: p.repository ?? "" }));
}

function npm() {
  const out = new Map();
  const visit = (name, from) => {
    let dir = from;
    let found = null;
    for (;;) {
      const c = join(dir, "node_modules", name, "package.json");
      if (existsSync(c)) { found = c; break; }
      const up = dirname(dir);
      if (up === dir) return;
      dir = up;
    }
    const p = JSON.parse(readFileSync(found, "utf8"));
    const key = `${p.name}@${p.version}`;
    if (out.has(key)) return;
    const license = typeof p.license === "string" ? p.license : p.license?.type ?? "see its repository";
    const url = typeof p.repository === "string" ? p.repository : p.repository?.url ?? "";
    out.set(key, { name: p.name, version: p.version, license, url: url.replace(/^git\+/, "") });
    for (const d of Object.keys(p.dependencies ?? {})) visit(d, dirname(found));
  };
  for (const d of Object.keys(pkg.dependencies ?? {})) visit(d, appDir);
  // Workspace packages of this repository are ours, not third party.
  return [...out.values()].filter((p) => !existsSync(join(root, "packages", p.name)));
}

const table = (rows) => ["| Package | Version | Licence |", "|---|---|---|",
  ...rows.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))
    .map((r) => `| ${r.url ? `[${r.name}](${r.url})` : r.name} | ${r.version} | ${r.license} |`)].join("\n");

const c = crates();
const n = npm();
const text = `# Third-party software in ${pkg.productName ?? app}

Generated by \`node scripts/third_party.mjs ${app}\`; do not edit. Each
package's licence text is in its source, at the version listed.

## Rust crates (${c.length})

${table(c)}

## Window (npm, ${n.length})

${table(n)}
`;
const file = join(appDir, "THIRD_PARTY.md");
if (flag === "--check") {
  if (!existsSync(file) || readFileSync(file, "utf8") !== text) {
    console.error(`${file} is stale: run node scripts/third_party.mjs ${app}`);
    process.exit(1);
  }
} else {
  writeFileSync(file, text);
  console.log(`${file}: ${c.length} crates, ${n.length} npm packages`);
}
