/// Hang up any live call. Nothing to do in a build without `calls`.
pub(crate) async fn shutdown_calls(app: &AppHandle) {
    #[cfg(feature = "calls")]
    {
        let vox = app.state::<vox::VoxState>();
        vox::shutdown(app, &vox).await;
    }
    #[cfg(not(feature = "calls"))]
    let _ = app;
}

/// Whether a call is live — it counts as presence for the idle lock.
pub(crate) fn in_call(app: &AppHandle) -> bool {
    #[cfg(feature = "calls")]
    {
        vox::in_call(app)
    }
    #[cfg(not(feature = "calls"))]
    {
        let _ = app;
        false
    }
}


