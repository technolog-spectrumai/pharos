"""The generated YAML must round-trip, and must stay in step with build.rs.

build.rs parses with ``deny_unknown_fields`` and every field required, so a
schema change on the Rust side has to break a test here rather than a build
half an hour later.
"""

from __future__ import annotations

import copy

import pytest
import yaml

import yaml_gen
from yaml_gen import leaf_paths, render


def test_round_trips_the_canonical_config(cfg):
    assert yaml.safe_load(render(cfg)) == cfg


def test_round_trips_a_mutated_config(cfg):
    cfg["maps"]["enabled"] = False
    cfg["app"]["name"] = "Enigma Field"
    cfg["settings"]["idle_lock_mins"] = {"default": 0, "min": 0, "max": 1}
    cfg["network"]["max_frame_bytes"] = 32 * 1024 * 1024
    assert yaml.safe_load(render(cfg)) == cfg


def test_schema_matches_the_canonical_file(cfg, canonical):
    """The generated file must define exactly the keys build.rs expects."""
    generated = yaml.safe_load(render(cfg))
    assert leaf_paths(generated) == leaf_paths(canonical)


def test_scalar_paths_cover_every_leaf(canonical):
    """Nothing may be rendered by accident — every leaf is declared."""
    declared = set(yaml_gen.SCALAR_PATHS)
    assert declared == leaf_paths(canonical)


def test_booleans_render_lowercase(cfg):
    cfg["maps"]["enabled"] = True
    cfg["p2p"]["allow_hosted_relays"] = False
    text = render(cfg)
    assert "enabled: true" in text
    assert "allow_hosted_relays: false" in text
    assert "True" not in text and "False" not in text


def test_header_records_provenance(cfg):
    text = render(cfg, "plus (unmodified gates)")
    assert text.startswith("# @generated by tools/enigma_builder")
    assert "# Derived from preset: plus (unmodified gates)" in text
    assert "ENIGMA_EDITION=custom" in text


def test_ambiguous_strings_are_quoted(cfg):
    """A version like 1.0 is a float in bare YAML — it has to survive as text."""
    cfg["app"]["version"] = "1.0"
    cfg["app"]["name"] = "Enigma: Field Edition"
    loaded = yaml.safe_load(render(cfg))
    assert loaded["app"]["version"] == "1.0"
    assert loaded["app"]["name"] == "Enigma: Field Edition"


def test_dollar_in_a_value_is_not_re_substituted(cfg):
    """Values are inserted once; a literal $ must not be read as a placeholder."""
    cfg["app"]["name"] = "Enigma $app_version"
    assert yaml.safe_load(render(cfg))["app"]["name"] == "Enigma $app_version"


def test_missing_field_raises_rather_than_emitting_a_partial_file(cfg):
    del cfg["maps"]["enabled"]
    with pytest.raises(KeyError, match="maps.enabled"):
        render(cfg)


def test_missing_clamp_field_raises(cfg):
    del cfg["settings"]["idle_lock_mins"]["max"]
    with pytest.raises(KeyError, match="settings.idle_lock_mins.max"):
        render(cfg)


def test_output_is_deterministic(cfg):
    assert render(cfg) == render(copy.deepcopy(cfg))


def test_clamp_rows_keep_the_canonical_order(cfg):
    text = render(cfg)
    positions = [text.index(f"  {key}: {{") for key in yaml_gen.SETTINGS_KEYS]
    assert positions == sorted(positions)
