"""Render a complete ``build_config.custom.yaml`` from a config dict.

A ``string.Template`` rather than ``yaml.safe_dump`` because the checked-in
configs are self-documenting: the comments are the only place several of these
knobs are explained, and a build config that arrives without them is a config
nobody can safely hand-edit. We never round-trip an existing file — the form is
always materialized whole — so comment-preserving YAML libraries buy nothing.

``build.rs`` parses this with ``deny_unknown_fields`` and every field required,
so the template must stay exactly in step with the canonical
``build_config.yaml``. ``tests/test_yaml_gen.py`` compares the two key sets.
"""

from __future__ import annotations

import json
from string import Template
from typing import Any

import yaml

from validation import SETTINGS_FLOORS, get_path

SETTINGS_KEYS: tuple[str, ...] = tuple(SETTINGS_FLOORS)
CLAMP_FIELDS = ("default", "min", "max")

NETWORK_KEYS = (
    "max_frame_bytes",
    "onion_port",
    "max_redirects",
    "tor_write_timeout_secs",
    "tor_handshake_timeout_secs",
)

SCALAR_PATHS = (
    "app.name",
    "app.identifier",
    "app.version",
    "p2p.allow_hosted_relays",
    "dht.enabled",
    "crypto.mls_ciphersuite",
    "crypto.at_rest_aead",
    "crypto.kdf.algorithm",
    "crypto.kdf.m_cost_kib",
    "crypto.kdf.t_cost",
    "crypto.kdf.p_cost",
    "calls.enabled",
    "contacts.enabled",
    "calendar.enabled",
    "peers.enabled",
    "maps.enabled",
    "keyring.enabled",
    "lock.pin_unlock",
    "devices.allow_linking",
    "features.use_tor",
    "features.stable_onion",
    "features.dht_discovery",
    "features.dht_nick_publish",
    "features.file_integrity",
    *(f"network.{key}" for key in NETWORK_KEYS),
    *(
        f"settings.{key}.{field}"
        for key in SETTINGS_KEYS
        for field in CLAMP_FIELDS
    ),
)


def _placeholder(path: str) -> str:
    return path.replace(".", "_")


def _scalar(value: Any) -> str:
    """Render one YAML scalar, quoting only when the bare form would change it."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    text = str(value)
    try:
        bare_is_faithful = yaml.safe_load(text) == text
    except yaml.YAMLError:
        bare_is_faithful = False
    if bare_is_faithful and text == text.strip() and "#" not in text:
        return text
    # JSON string escapes are a subset of YAML's double-quoted style.
    return json.dumps(text)


def _settings_block(cfg: dict[str, Any]) -> str:
    """The nine clamp rows, in the canonical file's order and flow style."""
    rows = []
    for key in SETTINGS_KEYS:
        values = []
        for field in CLAMP_FIELDS:
            value = get_path(cfg, f"settings.{key}.{field}")
            if value is None:
                raise KeyError(f"build config is missing settings.{key}.{field}")
            values.append(f"{field}: {_scalar(value)}")
        rows.append(f"  {key}: {{ {', '.join(values)} }}")
    return "\n".join(rows)


TEMPLATE = Template(
    """# @generated by tools/enigma_builder — DO NOT hand-edit; regenerate via the Builder.
# Derived from preset: $preset_provenance
# Built with ENIGMA_EDITION=custom. This file is gitignored and is the only
# config the Builder ever writes; light/plus/pro stay as the product line
# defines them (pland.md).
#
# Baked in at COMPILE TIME by src-tauri/build.rs, which validates this file and
# generates the `build_config` consts from it. The shipped binary never reads it.

app:
  # Must MATCH tauri.conf.json (productName / identifier / version), which stays
  # authoritative for the native bundle — build.rs asserts equality.
  name: $app_name
  identifier: $app_identifier
  version: $app_version

p2p:
  # false = iroh runs with RelayMode::Disabled and all hosted discovery is off
  # (pkarr/DNS publishing AND the Mainline DHT, which rides the same endpoint).
  # Direct QUIC (ticket/QR bootstrap) and the Tor onion transport keep working,
  # but reconnecting to a bare NodeId does not.
  allow_hosted_relays: $p2p_allow_hosted_relays

dht:
  # false = the Mainline DHT is out of reach: no rendezvous publishing, no
  # ticketless join-by-room-code, no nickname directory, no presence.
  # Requires p2p.allow_hosted_relays — build.rs rejects the combination.
  # This is the BUILD gate; features.dht_discovery below is the runtime default.
  enabled: $dht_enabled

crypto:
  # Declarations, ASSERTED at compile time against the vendored crates
  # (cryptorotor/rotor_core, cryptorotor/gervasius). Changing these strings does
  # NOT change the algorithms — change the crates, then update the declaration.
  mls_ciphersuite: $crypto_mls_ciphersuite
  at_rest_aead: $crypto_at_rest_aead
  kdf:
    algorithm: $crypto_kdf_algorithm
    # Argon2id costs for NEWLY created vaults. Existing vaults are untouched:
    # each vault header records its own costs, so old data always unlocks.
    m_cost_kib: $crypto_kdf_m_cost_kib
    t_cost: $crypto_kdf_t_cost
    p_cost: $crypto_kdf_p_cost

calls:
  # false = no 1:1 voice calls: no Calls tab, /calls redirects, useVoxCall is
  # never instantiated, and every vox_* command fails with CALLS_DISABLED.
  enabled: $calls_enabled

contacts:
  # false = no Contacts: no tab, /contacts redirects, and useRoomInvites is
  # never instantiated (direct room invites neither sent nor received).
  enabled: $contacts_enabled

calendar:
  # false = no Calendar: no tab, /calendar redirects, useMeetings is never
  # instantiated (no meetings, no polls, no reminder tick).
  enabled: $calendar_enabled

peers:
  # false = no peer sync: the `enigma/plink/0` ALPN is not registered,
  # usePeerSync is never instantiated, peer_* fail with PEERS_DISABLED.
  enabled: $peers_enabled

maps:
  # false = no Maps: no Map tab, /map redirects, every map_* command fails with
  # MAPS_DISABLED. The app NEVER fetches tiles itself — region packages come
  # from tools/map_packager and are imported from the device.
  enabled: $maps_enabled

lock:
  pin_unlock: $lock_pin_unlock

keyring:
  # false = no key ring (one passphrase locking MANY local files): every
  # keyring_* command fails with KEYRING_DISABLED. Per-file locking
  # (local_lock) is always in — this gates only the shared ring.
  enabled: $keyring_enabled

devices:
  # false = no device linking: every devlink_* command fails with
  # DEVLINK_DISABLED and the Settings→Devices tab is hidden. Also gates
  # Files→Devices file sync.
  allow_linking: $devices_allow_linking

features:
  # Initial values for a NEW profile's toggles. Runtime Settings switches still
  # override per profile; profiles saved by any build keep their stored values.
  use_tor: $features_use_tor
  stable_onion: $features_stable_onion
  dht_discovery: $features_dht_discovery
  dht_nick_publish: $features_dht_nick_publish
  file_integrity: $features_file_integrity

settings:
  # Defaults + clamp bounds for the user-tunable settings. The encrypted KV
  # store (ns p2p:settings) remains the runtime source of truth; these only
  # seed and bound it. Build-checked invariant: min <= default <= max.
$settings_block

network:
  # WIRE-INTEROP: peers in one room must agree on max_frame_bytes — it caps the
  # Tor transport frame AND the iroh-gossip message size. Change only in
  # lockstep across a fleet.
  max_frame_bytes: $network_max_frame_bytes
  # Not interop-sensitive: the virtual onion port rides inside each ticket, so
  # joiners always use the ticket's value; changing it affects new tickets only.
  onion_port: $network_onion_port
  # Local-only tuning (no wire impact).
  max_redirects: $network_max_redirects
  tor_write_timeout_secs: $network_tor_write_timeout_secs
  tor_handshake_timeout_secs: $network_tor_handshake_timeout_secs
"""
)


def render(cfg: dict[str, Any], provenance: str = "custom") -> str:
    """Render ``cfg`` as the full custom build config.

    Raises KeyError via ``Template.substitute`` if the config is missing a
    field, which is the desired failure: a partial YAML would fail the build
    much later with a serde error.
    """
    mapping: dict[str, str] = {
        "preset_provenance": provenance.replace("\n", " "),
        "settings_block": _settings_block(cfg),
    }
    for path in SCALAR_PATHS:
        if path.startswith("settings."):
            continue  # rendered by _settings_block, as one flow-style row each
        value = get_path(cfg, path)
        if value is None:
            raise KeyError(f"build config is missing {path}")
        mapping[_placeholder(path)] = _scalar(value)
    # One pass only: substituted values may themselves contain a literal '$'.
    return TEMPLATE.substitute(mapping)


def leaf_paths(cfg: dict[str, Any], prefix: str = "") -> set[str]:
    """Every dotted leaf path in a nested config — used by the drift test."""
    found: set[str] = set()
    for key, value in cfg.items():
        path = f"{prefix}{key}"
        if isinstance(value, dict):
            found |= leaf_paths(value, f"{path}.")
        else:
            found.add(path)
    return found
