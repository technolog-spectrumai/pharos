# Where crypto_rotor is, and how a build finds it.
#
# Sourced, never executed:
#
#   . "$SCRIPT_DIR/scripts/rotor_path.sh"
#   resolve_rotor            # sets ROTOR_PATH, or dies with a useful message
#
# CryptoRotor became its own repository on 2026-09-08. The manifests
# (apps/enigma/src-tauri/Cargo.toml, protasius/Cargo.toml) name it by a
# RELATIVE path that assumes a sibling checkout:
#
#   dev/
#   ├── rotor/crypto_rotor/   ← the crypto crates
#   └── enigma/enigma/        ← this repo
#
# That default needs no configuration and is what CI and a fresh clone get.
#
# WHY A SCRIPT AND NOT AN ENV VAR IN THE MANIFEST: cargo does not expand
# environment variables in a `path = "..."` dependency — `${ROTOR_PATH}/…`
# fails with "No such file or directory". Verified, not assumed. The only
# mechanism that redirects a PATH dependency is a `paths = [...]` override in
# `.cargo/config.toml`; `[patch.crates-io]` does NOT work here, because it
# patches registry sources and these are path sources. Also verified.
#
# So: the committed relative paths are the contract, and `ROTOR_PATH` is the
# escape hatch for a checkout that is laid out differently. Setting it writes a
# gitignored `.cargo/config.toml` with a `paths` override; unsetting it removes
# that file and the default applies again.

# Absolute path to the default sibling checkout, from the repo root.
rotor_default() {
  # $1 is the repo root (where build_desktop.sh lives).
  printf '%s' "$(cd "$1/../../rotor/crypto_rotor" 2>/dev/null && pwd)"
}

# Confirm a directory really is crypto_rotor before a build trusts it — a wrong
# path otherwise surfaces as a confusing cargo error deep in the dependency
# graph rather than as "you pointed me at the wrong place".
rotor_is_valid() {
  [ -n "$1" ] && [ -f "$1/Cargo.toml" ] \
    && [ -f "$1/rotor_core/Cargo.toml" ] && [ -f "$1/gervasius/Cargo.toml" ]
}

# Resolve, validate, and wire it up. $1 is the repo root.
#
# Sets ROTOR_PATH. Writes .cargo/config.toml ONLY when the caller pointed
# somewhere other than the default, so an ordinary checkout stays free of
# generated files.
resolve_rotor() {
  local root="$1" default
  default="$(rotor_default "$root")"

  if [ -n "${ROTOR_PATH:-}" ]; then
    # Given explicitly: normalise to absolute so the override is unambiguous.
    ROTOR_PATH="$(cd "$ROTOR_PATH" 2>/dev/null && pwd || printf '%s' "$ROTOR_PATH")"
  else
    ROTOR_PATH="$default"
  fi

  if ! rotor_is_valid "$ROTOR_PATH"; then
    # Self-contained: these scripts have no shared die(), and a helper that
    # assumed one would break whichever caller forgot to define it.
    cat >&2 <<EOF
ERROR: crypto_rotor not found at ${ROTOR_PATH:-<unset>}


The crypto crates (rotor_core, gervasius) live in their own repository:
  git clone git@gitlab.com:janhagit-group/crypto_rotor.git

Check it out beside this repo —
  dev/rotor/crypto_rotor  and  dev/enigma/enigma
— or point at it explicitly:
  ROTOR_PATH=/path/to/crypto_rotor \$0
EOF
    exit 1
  fi

  if [ "$ROTOR_PATH" = "$default" ]; then
    # The committed relative paths already resolve here; a generated override
    # would be noise, and a STALE one would silently win over the default.
    rm -f "$root/.cargo/config.toml"
    rmdir "$root/.cargo" 2>/dev/null || true
  else
    mkdir -p "$root/.cargo"
    cat > "$root/.cargo/config.toml" <<EOF
# GENERATED by scripts/rotor_path.sh — do not edit, do not commit.
# Redirects the crypto crates to a checkout outside the default sibling layout.
# Delete this file (or unset ROTOR_PATH and re-run) to go back to the default.
paths = ["$ROTOR_PATH"]
EOF
  fi
  export ROTOR_PATH
}
