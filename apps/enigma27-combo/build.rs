//! The combo window is Enigma27's `AppWindow` with more in it. Slint's generated Rust API
//! of a component that *inherits* another does not include the base's properties, so
//! Enigma27's glue could not drive it; instead this script makes the window from
//! `apps/enigma27/ui/app.slint` at build time (into OUT_DIR, never checked in):
//! renamed `ComboWindow`, title and left inset set, `ui/window-body.slint.in` (the rail
//! and the Lighthouse view) added at its end, and the Lighthouse view imported from
//! `apps/pharos-lighthouse/ui/app.slint`. Its own imports (theme, widgets) resolve in
//! Enigma27's ui folder through the include path.

use std::path::PathBuf;

fn main() {
    let here = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let e27 = here.join("../enigma27/ui");
    let lh = here.join("../pharos-lighthouse/ui");
    for p in [e27.join("app.slint"), e27.join("theme.slint"), e27.join("widgets.slint"), lh.join("app.slint"), lh.join("widgets.slint"), here.join("ui/rail.slint"), here.join("ui/window-body.slint.in")] {
        println!("cargo:rerun-if-changed={}", p.display());
    }
    let app = std::fs::read_to_string(e27.join("app.slint")).expect("enigma27 ui/app.slint");
    let body = std::fs::read_to_string(here.join("ui/window-body.slint.in")).expect("window-body.slint.in");
    let mut s = app
        .replacen("export component AppWindow inherits Window {", "export component ComboWindow inherits Window {", 1)
        .replacen("    title: \"Enigma27\";", "    title: \"Enigma27 Combo\";", 1)
        .replacen("    preferred-width: 1100px;", "    preferred-width: 1300px;", 1)
        .replacen("    min-width: 320px;", "    min-width: 900px;", 1)
        .replacen("    in property <length> inset-left: 0px;", "    in property <length> inset-left: 210px;", 1);
    assert!(s.contains("ComboWindow") && s.contains("Enigma27 Combo") && s.contains("inset-left: 210px"), "enigma27's app.slint changed shape");
    let end = s.trim_end().rfind('}').expect("closing brace");
    s.truncate(end);
    s.push_str(&body);
    s.push_str("}\n");
    let imports = format!(
        "// GENERATED by apps/enigma27-combo/build.rs from apps/enigma27/ui/app.slint; do not edit.\nimport {{ LighthouseView, Lh, LhScreen }} from \"{}\";\nimport {{ RailItem, RailHeader }} from \"{}\";\nexport {{ Lh, LhScreen }}\n",
        lh.join("app.slint").display(),
        here.join("ui/rail.slint").display()
    );
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("combo.slint");
    std::fs::write(&out, imports + &s).unwrap();
    let cfg = slint_build::CompilerConfiguration::new().with_style("fluent".into()).with_include_paths(vec![e27]);
    slint_build::compile_with_config(&out, cfg).expect("compile the combo window");
}
